// 自动加载下一话的**规则**：一次最多把多少张图接进来。
//
// 为什么单独一个文件（2026-10-02）：这条规则本身很简单，但按"话数"封顶是错的 ——
// 短话一话只有几张（按 3 话限，一眼看完就没得接了），长话一话两百张（3 话就是 600 张，
// 拿流量和内存赌用户不会读那么远）。按**张数**封顶才两种情况都对。
//
// 拆出来还有一个好处：这条判断能**直接单测**，不用去搭一个"接满 60 张"的阅读器场景
//（那种用例要造 6 话 × 10 张以上的假书，跑起来又慢又容易挂）。
library;

/// 一次最多自动接多少张图（不是多少话）。
const int kMaxAutoAppendImages = 60;

/// 还能不能再往下接一话。
///
/// [appendedImages] = 已经自动接上来的张数（不含当前这一话自己的张数）。
bool canAutoAppendMore(int appendedImages) =>
    appendedImages < kMaxAutoAppendImages;
